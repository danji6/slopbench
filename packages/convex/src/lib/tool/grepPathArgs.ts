/** Keep search patterns as data and pattern/ignore files as checked paths. */
export function grepPathValues(program: string, args: string[]) {
  const { operands, options, complete } = parseShellOptionArgs(
    args,
    program === 'rg' ? RG_OPTIONS : GREP_OPTIONS,
  )
  const filesOnly =
    program === 'rg' && options.some(({ flag }) => flag === '--files')
  const hasPattern = options.some(
    ({ flag }) => PATTERN_FLAGS.has(flag) || flag === '-f' || flag === '--file',
  )
  const files = options
    .filter(({ flag }) => FILE_FLAGS.has(flag) || flag === '--exclude-from')
    .flatMap(({ value }) => (value === undefined ? [] : [value]))
  const paths = filesOnly || hasPattern ? operands : operands.slice(1)
  return {
    values: [...files, ...paths].filter((value) => value !== '-'),
    complete,
  }
}
