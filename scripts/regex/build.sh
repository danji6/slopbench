#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/../.."
export GOTOOLCHAIN=go1.26.2
go_tool=${GO:-go}
go_root=$("$go_tool" env GOROOT)
output=packages/convex/src/lib/regex

GOOS=js GOARCH=wasm "$go_tool" build -trimpath -ldflags='-s -w -buildid=' \
  -o "$output/matcher.wasm" scripts/regex/matcher.go
chmod 644 "$output/matcher.wasm"
# The runtime must be from the same toolchain as the compiled module.
{
  printf '/* eslint-disable */\n/* Generated by scripts/regex/build.sh */\n'
  cat "$go_root/lib/wasm/wasm_exec.js"
} > "$output/wasm.exec.js"
cp "$go_root/LICENSE" "$output/LICENSE"
